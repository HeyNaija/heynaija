import { expect, test } from '@playwright/test'

test('login starts and resumes flows, preserving CSRF fields and submission target', async ({ page, request }) => {
  await page.goto('/login')
  await expect(page.getByLabel('Email address')).toBeVisible()
  await expect(page).toHaveURL(/\/login\?flow=login$/)
  await expect(page.locator('input[name="csrf_token"]')).toHaveValue('csrf-fixture')
  await page.getByLabel('Email address').fill('ada@example.test')
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  await expect(page).toHaveURL(/\/auth-error\?id=submitted$/)
  const calls = await (await request.get('http://127.0.0.1:4407/__requests')).json()
  expect(calls.some((call: { path: string; cookie: string }) => call.path === '/self-service/login/flows' && call.cookie.includes('csrf_fixture=raw%2Fvalue'))).toBe(true)
  expect(calls.some((call: { path: string; body: string }) => call.path === '/self-service/login' && call.body.includes('csrf_token=csrf-fixture'))).toBe(true)
  await page.goto('/login?flow=expired')
  await expect(page.getByLabel('Email address')).toBeVisible()
  await expect(page).toHaveURL(/flow=login$/)
})

test('reauthentication locks the email and retains the logout link', async ({ page, context }) => {
  await context.addCookies([{ name: 'hn_session', value: 'fixture', url: 'http://127.0.0.1:3307' }])
  await page.goto('/login?flow=refresh')
  await expect(page.getByLabel('Email address')).toHaveValue('ada@example.test')
  await expect(page.getByLabel('Email address')).toHaveAttribute('readonly', '')
  await expect(page.getByRole('link', { name: 'Sign out', exact: true })).toHaveAttribute('href', '/logout?to=%2Fapi%2Fv1%2Fauth%2Flogout%3Ftoken%3Dfixture')
})

test('signup keeps admission cookies required; verification and errors render through the facade', async ({ page, context }) => {
  await page.goto('/signup?flow=registration')
  await expect(page).toHaveURL(/\/join$/)
  await page.getByLabel('Invite code', { exact: true }).fill('HN-FIXTURE')
  await page.getByLabel('I am 18 or older', { exact: true }).check()
  await page.getByRole('button', { name: 'Check invite code' }).click()
  await expect(page.getByLabel('Handle', { exact: true })).toBeVisible()
  await expect(page).toHaveURL(/\/signup\?flow=registration$/)
  const cookies = await context.cookies()
  expect(cookies.find((cookie) => cookie.name === 'hn_invite')?.value).toBe('HNFIXTURE')
  expect(cookies.find((cookie) => cookie.name === 'hn_age')?.value).toBe('18-plus')
  await page.goto('/verification?flow=verification')
  await expect(page.locator('form')).toHaveAttribute('action', /\/api\/v1\/auth\/flows\/verification\?flow=verification$/)
  await page.goto('/auth-error?id=fixture')
  await expect(page.getByText('Fixture flow expired')).toBeVisible()
})

test('settings retain email confirmation flow and only clear completed notices', async ({ page, context, request }) => {
  await context.addCookies([{ name: 'hn_session', value: 'fixture', url: 'http://127.0.0.1:3307' }, { name: 'private_other', value: 'secret', url: 'http://127.0.0.1:3307' }])
  await page.goto('/settings?flow=email-change')
  await expect(page.getByLabel('Code sent to your new email')).toBeVisible()
  await expect(page).toHaveURL(/flow=email-change$/)
  await expect(page.getByRole('heading', { name: 'Connected accounts' })).toBeVisible()
  await expect(page.getByLabel('Email address', { exact: true })).toBeDisabled()
  await page.goto('/settings?flow=notice')
  await expect(page.getByText('Saved fixture notice')).toBeVisible()
  await expect(page).toHaveURL(/\/settings$/)
  const calls = await (await request.get('http://127.0.0.1:4407/__requests')).json()
  const meCalls = calls.filter((call: { path: string }) => call.path === '/v1/me')
  expect(meCalls.length).toBeGreaterThan(0)
  expect(meCalls.every((call: { cookie: string }) => call.cookie === 'hn_session=fixture')).toBe(true)
})

test('logout preserves local target validation and cache invalidation before provider redirect', async ({ request }) => {
  const refused = await request.get('/logout?to=https%3A%2F%2Fevil.test', { maxRedirects: 0 })
  expect(refused.status()).toBe(303)
  expect(refused.headers().location).toBe('/')
  const logout = await request.get('/logout?to=%2Fapi%2Fv1%2Fauth%2Flogout%3Ftoken%3Dfixture', { maxRedirects: 0, headers: { cookie: 'hn_session=fixture; private_other=secret' } })
  expect(logout.status()).toBe(303)
  expect(logout.headers().location).toBe('/api/v1/auth/logout?token=fixture')
  const completed = await request.get(logout.headers().location!, { maxRedirects: 0, headers: { cookie: 'hn_session=fixture' } })
  expect(completed.status()).toBe(303)
  expect(completed.headers().location).toBe('/auth-error')
  const calls = await (await request.get('http://127.0.0.1:4407/__requests')).json()
  expect(calls.some((call: { path: string; cookie: string }) => call.path === '/self-service/logout' && call.cookie === 'hn_session=fixture')).toBe(true)
})
