import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { AVAILABILITY, CATEGORIES, PRIORITIES, ROADMAP, STATUSES, roadmapGroups, statusCounts } from '../apps/web/lib/roadmap.ts'

export const markdownPath = new URL('../docs/FEATURE_ROADMAP.md', import.meta.url)
const cell = (text) => text.replaceAll('|', '\\|').replaceAll('\n', ' ')

export function renderRoadmap(roadmap = ROADMAP) {
  const counts = statusCounts(roadmap.features)
  const lines = [
    '# HeyNaija feature roadmap', '',
    '> Generated from `docs/feature-roadmap.json`. Do not edit this file by hand.',
    '> Run `pnpm roadmap:generate`; `pnpm roadmap:check` validates the registry and rejects drift.', '',
    roadmap.scope, '',
    'This tracks product development, not formal governance decisions. Priority means importance, not completion. No delivery dates or launch-readiness percentages are implied. The public readable counterpart is `/progress`, which links to this document.', '',
    '## Status and availability', '',
    ...Object.entries(STATUSES).map(([key, status]) => `- **${status.label}** (\`${key}\`): ${status.definition}`), '',
    ...Object.entries(AVAILABILITY).map(([key, label]) => `- **${label}** (\`${key}\`)${key === 'production' ? ': the owner confirmed the feature working in production; this does not show which revision is deployed there.' : key === 'staging' ? ': staging is recorded in deployment documentation; it is not production or proof this local revision is deployed.' : key === 'unknown' ? ': code and test evidence do not establish live availability.' : ': the described feature is unavailable.'}`), '',
    '## Feature counts', '',
    '| Implemented | Partial | Planned | Blocked | Total |', '| --- | --- | --- | --- | --- |',
    `| ${counts.implemented} | ${counts.partial} | ${counts.planned} | ${counts.blocked} | ${roadmap.features.length} |`, '',
    '## Priority order', '',
    ...Object.entries(PRIORITIES).map(([priority, label]) => `- **${priority}** — ${label}`), '',
  ]
  for (const group of roadmapGroups(roadmap.features)) {
    lines.push(`## ${group.priority} — ${PRIORITIES[group.priority]}`, '')
    for (const category of group.categories) {
      lines.push(`### ${CATEGORIES[category.category]}`, '')
      for (const feature of category.features) {
        lines.push(`#### ${feature.name}`, '', `- **ID:** \`${feature.id}\``, `- **Priority:** ${feature.priority} · **Status:** ${STATUSES[feature.status].label} · **Availability:** ${AVAILABILITY[feature.availability]}`, `- **Description:** ${cell(feature.description)}`)
        if (feature.caveat) lines.push(`- **Remaining work / caveat:** ${cell(feature.caveat)}`)
        if (feature.dependency?.length) lines.push(`- **Dependencies:** ${feature.dependency.map((id) => `\`${id}\``).join(', ')}`)
        lines.push(`- **Inspected evidence:** ${feature.evidence.map((path) => `\`${path}\``).join(', ')}`)
        if (feature.notes) lines.push(`- **Audit notes:** ${cell(feature.notes)}`)
        lines.push('')
      }
    }
  }
  lines.push('## Maintaining this registry', '',
    'Schema version 1 is validated in `apps/web/lib/roadmap.ts`, shared by the generator and server-rendered page. Every feature requires a stable kebab-case ID, name, one-sentence description, known category, P0–P3 priority, lifecycle status, availability and inspected evidence paths. Partial and blocked entries require a separate public caveat. Implemented entries require both application and test evidence; a migration or placeholder alone does not qualify. Dependencies must refer to other feature IDs and must not form cycles.', '',
    'Evidence paths and operator notes appear only in this developer document. Public caveats must be safe to publish and must not reveal internal security details. Record a verification date only with an actual verification record; do not manufacture a latest-update date when generating.', '',
    'The local audit does not attest to the live staging revision, production launch, provider approval, legal adoption or completion of an operational rehearsal. Confirm those independently before changing availability or removing a caveat.', '')
  return lines.join('\n')
}

export async function checkRoadmap() {
  const existing = await readFile(markdownPath, 'utf8')
  if (existing !== renderRoadmap()) throw new Error('FEATURE_ROADMAP.md is out of date. Run pnpm roadmap:generate.')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv[2] === '--check') {
    await checkRoadmap()
    console.log(`Roadmap valid and in sync (${ROADMAP.features.length} features).`)
  } else if (process.argv.length === 2) {
    await writeFile(markdownPath, renderRoadmap())
    console.log(`Generated docs/FEATURE_ROADMAP.md (${ROADMAP.features.length} features).`)
  } else {
    throw new Error('Usage: roadmap.mjs [--check]')
  }
}
